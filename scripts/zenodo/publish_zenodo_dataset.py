#!/usr/bin/env python3
"""Publish or stage a BioCIRV public dataset release on Zenodo via REST API.

Unlike the software repository release (`CITATION.cff` + GitHub-Zenodo webhook,
which archives the entire Git repository as `type: software` under DOI
`10.5281/zenodo.19443582`), the BioCIRV Public Schema export is a standalone
`dataset` deposition (`upload_type: "dataset"`).

This script:
1. Connects to Zenodo Sandbox (`https://sandbox.zenodo.org/api`) by default or
   Zenodo Production (`https://zenodo.org/api`) when `--production` is passed.
2. Creates either a fresh deposition or a new version draft of an existing
   Zenodo Concept/Deposition ID (`--existing-deposition-id`).
3. Uploads all CSV/Parquet/Markdown files from the specified export directory
   to the deposition's bucket URL.
4. Attaches the contributor & dataset metadata JSON generated by
   `sync_zenodo_authors.py`.
5. Leaves the deposition as a reviewable **Draft** on Zenodo unless `--publish`
   is explicitly passed (since minting a Zenodo DOI is permanent).
"""

from __future__ import annotations

import argparse
import json
import mimetypes
import os
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

ZENODO_SANDBOX_API = "https://sandbox.zenodo.org/api"
ZENODO_PROD_API = "https://zenodo.org/api"


def zenodo_request(
    url: str,
    token: str,
    method: str = "GET",
    json_payload: dict[str, Any] | None = None,
    raw_bytes: bytes | None = None,
    content_type: str = "application/json",
) -> dict[str, Any]:
    """Execute an authenticated HTTP request against the Zenodo REST API."""
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/json",
    }
    data: bytes | None = None
    if json_payload is not None:
        data = json.dumps(json_payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    elif raw_bytes is not None:
        data = raw_bytes
        headers["Content-Type"] = content_type

    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=120) as resp:
        body = resp.read().decode("utf-8")
        return json.loads(body) if body else {}


def create_or_version_deposition(
    api_base: str,
    token: str,
    existing_deposition_id: str | None = None,
) -> dict[str, Any]:
    """Create a new Zenodo deposition or a new version draft of an existing record."""
    if existing_deposition_id:
        url = f"{api_base}/deposit/depositions/{existing_deposition_id}/actions/newversion"
        resp = zenodo_request(url, token, method="POST")
        latest_draft_url = resp.get("links", {}).get("latest_draft")
        if not latest_draft_url:
            raise RuntimeError("Zenodo did not return a 'latest_draft' link for newversion.")
        draft = zenodo_request(latest_draft_url, token, method="GET")
        # Clear previous version's files from the new draft before uploading new files
        for prev_file in draft.get("files", []):
            file_id = prev_file.get("id")
            if file_id:
                zenodo_request(f"{latest_draft_url}/files/{file_id}", token, method="DELETE")
        return zenodo_request(latest_draft_url, token, method="GET")

    url = f"{api_base}/deposit/depositions"
    return zenodo_request(url, token, method="POST", json_payload={})


def upload_files_to_bucket(
    bucket_url: str,
    token: str,
    files: list[Path],
) -> list[dict[str, Any]]:
    """Upload dataset export files to the Zenodo deposition's bucket URL."""
    uploaded: list[dict[str, Any]] = []
    for file_path in files:
        mime_type, _ = mimetypes.guess_type(file_path.name)
        content_type = mime_type or "application/octet-stream"
        target_url = f"{bucket_url}/{file_path.name}"
        print(f"Uploading {file_path.name} ({file_path.stat().st_size} bytes)...")
        resp = zenodo_request(
            target_url,
            token=token,
            method="PUT",
            raw_bytes=file_path.read_bytes(),
            content_type=content_type,
        )
        uploaded.append(resp)
    return uploaded


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Stage or publish the BioCIRV Public Dataset to Zenodo."
    )
    parser.add_argument(
        "--metadata-json",
        type=Path,
        default=Path("scripts/zenodo/zenodo_metadata.preview.json"),
        help="Path to the Zenodo metadata JSON file generated by sync_zenodo_authors.py.",
    )
    parser.add_argument(
        "--data-dir",
        type=Path,
        required=True,
        help="Directory containing exported BioCIRV public schema CSV/Parquet files and data dictionary.",
    )
    parser.add_argument(
        "--existing-deposition-id",
        default=os.environ.get("ZENODO_DEPOSITION_ID", ""),
        help="Optional existing Zenodo Deposition ID to mint a new version under the same Concept DOI.",
    )
    parser.add_argument(
        "--production",
        action="store_true",
        help="Target Zenodo Production (zenodo.org) instead of Zenodo Sandbox (sandbox.zenodo.org).",
    )
    parser.add_argument(
        "--publish",
        action="store_true",
        help="Publish the deposition and permanently mint the DOI (default: save as reviewable Draft).",
    )
    args = parser.parse_args()

    token = os.environ.get("ZENODO_TOKEN", "")
    if not token:
        raise SystemExit("Error: Set ZENODO_TOKEN environment variable.")

    if not args.metadata_json.exists():
        raise SystemExit(f"Error: Metadata file not found: {args.metadata_json}")
    if not args.data_dir.exists():
        raise SystemExit(f"Error: Data directory not found: {args.data_dir}")

    files = sorted(p for p in args.data_dir.iterdir() if p.is_file())
    if not files:
        raise SystemExit(f"Error: No files found in {args.data_dir}")

    api_base = ZENODO_PROD_API if args.production else ZENODO_SANDBOX_API
    env_label = "PRODUCTION (zenodo.org)" if args.production else "SANDBOX (sandbox.zenodo.org)"
    print(f"Targeting Zenodo {env_label}...")

    metadata_payload = json.loads(args.metadata_json.read_text(encoding="utf-8"))
    deposition = create_or_version_deposition(
        api_base=api_base,
        token=token,
        existing_deposition_id=args.existing_deposition_id or None,
    )
    dep_id = deposition["id"]
    bucket_url = deposition["links"]["bucket"]
    prereserved_doi = (
        deposition.get("metadata", {}).get("prereserve_doi", {}).get("doi", "pending")
    )
    print(f"Created draft deposition ID={dep_id} (Pre-reserved DOI: {prereserved_doi})")

    upload_files_to_bucket(bucket_url=bucket_url, token=token, files=files)

    # Attach metadata (creators, contributors, description, license, related_identifiers)
    dep_url = f"{api_base}/deposit/depositions/{dep_id}"
    updated = zenodo_request(dep_url, token=token, method="PUT", json_payload=metadata_payload)
    html_url = updated.get("links", {}).get("latest_draft_html") or updated.get("links", {}).get("html")

    if args.publish:
        pub_url = f"{dep_url}/actions/publish"
        published = zenodo_request(pub_url, token=token, method="POST")
        doi = published.get("doi")
        record_url = published.get("links", {}).get("record_html")
        print(f"PUBLISHED! Permanent DOI: {doi} -> {record_url}")
    else:
        print(f"Saved as reviewable Zenodo Draft (NOT yet published): {html_url}")


if __name__ == "__main__":
    main()
